#!/usr/bin/env node
/**
 * C17 GATE — official schema validation + licence inventory, obligations and notices.
 *
 * Fails closed on every step: schema preflight, compilation, validation, inventory build,
 * bidirectional reconciliation, disposition governance, artifact write. Nothing is downloaded.
 *
 * Usage: node scripts/gate/licence-obligations.mjs --out <DIR> [--as-of YYYY-MM-DD]
 *                                                  [--expected-sha <SHA>]
 */
import { writeFileSync, mkdirSync, readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

import { deriveC16Expectation } from './generate-closures.mjs';
import { compileBomValidator, validateBom, VENDOR_DIR } from './lib/cyclonedx-schema.mjs';
import { buildTargetInventory, reconcileInventory, OBLIGATION_TABLE, CATEGORY_OBLIGATIONS } from './lib/license-closure.mjs';
import {
  loadLegalDispositions, validateLegalDispositions, unresolvedScopeKey,
} from './lib/legal-dispositions.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const TARGETS = Object.freeze(['production', 'development']);
const sha256 = (b) => createHash('sha256').update(b).digest('hex');

/** Deterministic JSON: sorted keys, stable separators, no timestamps anywhere. */
function canonicalJson(value) {
  const walk = (v) => {
    if (Array.isArray(v)) return v.map(walk);
    if (v !== null && typeof v === 'object') {
      return Object.fromEntries(Object.keys(v).sort().map((k) => [k, walk(v[k])]));
    }
    return v;
  };
  return `${JSON.stringify(walk(value), null, 2)}\n`;
}

function parseArgs(argv) {
  const out = { outDir: null, asOf: null, expectedSha: null };
  for (let i = 0; i < argv.length; i += 1) {
    const a = argv[i];
    const next = () => {
      const v = argv[i + 1];
      if (v === undefined || v.startsWith('--')) throw new Error(`${a} requires a value`);
      i += 1;
      return v;
    };
    if (a === '--out') out.outDir = next();
    else if (a === '--as-of') out.asOf = next();
    else if (a === '--expected-sha') out.expectedSha = next();
    else throw new Error(`unknown argument ${JSON.stringify(a)}`);
  }
  if (out.outDir === null) throw new Error('--out <DIR> is required');
  if (out.asOf === null) out.asOf = new Date().toISOString().slice(0, 10);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(out.asOf)) throw new Error('--as-of must be YYYY-MM-DD');
  return out;
}

function noticesMarkdown({ inventories, dispositions }) {
  const lines = [
    '# Third-party notices',
    '',
    'This file is GENERATED by `scripts/gate/licence-obligations.mjs` from the lockfile-derived',
    'C16 target closures joined with the packages materialized by a frozen install. It is not',
    'legal advice. It records what each package DECLARES and what its licence mechanically',
    'requires; it does not decide whether those requirements are met by any particular',
    'distribution.',
    '',
  ];
  for (const target of TARGETS) {
    const inv = inventories[target];
    const third = inv.components.filter((c) => !c.first_party);
    lines.push(`## Target: ${target}`, '');
    lines.push(`${third.length} third-party components; `
      + `${inv.components.length - third.length} first-party workspace packages carry no `
      + 'third-party obligation.', '');
    const byLicence = new Map();
    for (const c of third) {
      const key = c.declared_license;
      if (!byLicence.has(key)) byLicence.set(key, []);
      byLicence.get(key).push(c);
    }
    for (const licence of [...byLicence.keys()].sort()) {
      const cs = byLicence.get(licence).sort((a, b) => (a.purl < b.purl ? -1 : 1));
      lines.push(`### ${licence} (${cs.length})`, '');
      const cats = [...new Set(cs.map((c) => c.obligation_category))].sort();
      for (const cat of cats) {
        for (const o of CATEGORY_OBLIGATIONS[cat] ?? []) lines.push(`* ${o}`);
      }
      lines.push('');
      for (const c of cs) {
        const src = c.notice_text_source === 'spdx-canonical'
          ? 'no licence file shipped; canonical SPDX text applies'
          : `${c.licence_files.length} licence/notice file(s)`;
        lines.push(`* \`${c.purl}\` — ${src}`);
        for (const cr of (c.copyright ?? []).slice(0, 3)) lines.push(`  * ${cr}`);
      }
      lines.push('');
    }
    if (inv.unresolved.length > 0) {
      lines.push(`### Unresolved for ${target} (${inv.unresolved.length})`, '',
        'These are NOT classified. They require review; none of them is asserted to be',
        'acceptable by this file.', '');
      for (const u of inv.unresolved) lines.push(`* \`${u.purl}\` — ${u.issue}: ${u.detail}`);
      lines.push('');
    }
  }
  lines.push('## Reviewed legal dispositions', '');
  lines.push(dispositions.length === 0
    ? 'None. No unresolved licence matter has been signed off; every unresolved item above '
      + 'remains open.'
    : dispositions.map((d) => `* ${d.id} — \`${d.purl}\` (${d.target}): ${d.classification}`).join('\n'));
  lines.push('');
  return `${lines.join('\n')}`;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  mkdirSync(args.outDir, { recursive: true });
  const failures = [];
  const write = (name, text) => {
    writeFileSync(join(args.outDir, name), text);
    return { path: name, bytes: Buffer.byteLength(text), sha256: sha256(text) };
  };

  console.log('=== C17 LICENCE + OFFICIAL SCHEMA GATE ===');
  const headSha = spawnSync('git', ['rev-parse', 'HEAD'], { cwd: ROOT, encoding: 'utf8' }).stdout.trim();
  if (args.expectedSha !== null && headSha !== args.expectedSha) {
    failures.push(`HEAD is ${headSha}, --expected-sha is ${args.expectedSha}`);
  }
  console.log(`source SHA:  ${headSha}`);
  console.log(`as-of date:  ${args.asOf}`);

  // 1. Official schema, offline.
  const compiled = compileBomValidator(ROOT);
  if (!compiled.ok) failures.push(...compiled.problems);
  console.log(`\n-- official CycloneDX schema (${VENDOR_DIR}) --`);
  if (compiled.ok) {
    console.log(`  tag ${compiled.versions.schema_tag} commit ${compiled.versions.schema_commit}`);
    console.log(`  ajv ${compiled.versions.ajv} / ajv-formats ${compiled.versions.ajv_formats} / node ${compiled.versions.node}`);
  }

  const derived = deriveC16Expectation({ root: ROOT, asOfDate: args.asOf });
  const sbomResults = {};
  if (compiled.ok) {
    for (const target of TARGETS) {
      const text = derived.sbomTexts[target];
      const errs = validateBom(compiled.validate, JSON.parse(text), target);
      sbomResults[target] = { sha256: sha256(text), bytes: Buffer.byteLength(text), schema_errors: errs.length };
      if (errs.length > 0) failures.push(...errs);
      console.log(`  [${errs.length === 0 ? 'ok' : 'FAIL'}] ${target} sbom ${sha256(text).slice(0, 16)}… ${errs.length} schema error(s)`);
    }
  }

  // 2. Inventories from source + materialized packages.
  console.log('\n-- licence inventory --');
  const inventories = {};
  const allUnresolved = [];
  for (const target of TARGETS) {
    const inv = buildTargetInventory({ root: ROOT, target, closure: derived.closures[target] });
    const rec = reconcileInventory({ target, inventory: inv, closure: derived.closures[target] });
    if (rec.length > 0) failures.push(...rec);
    inventories[target] = inv;
    allUnresolved.push(...inv.unresolved);
    console.log(`  ${target}: ${inv.components.length} classified, ${inv.unresolved.length} unresolved, ${rec.length} reconciliation problem(s)`);
  }

  // 3. Legal dispositions — separate document, separate governance.
  console.log('\n-- legal dispositions --');
  const unresolvedKeys = new Set(allUnresolved.map(unresolvedScopeKey));
  let dispositions = [];
  try {
    const { doc } = loadLegalDispositions(ROOT);
    const r = validateLegalDispositions(doc, {
      runDate: args.asOf,
      root: ROOT,
      isTracked: (rel) => spawnSync('git', ['ls-files', '--error-unmatch', rel], { cwd: ROOT, encoding: 'utf8' }).status === 0,
      unresolvedKeys,
    });
    if (r.problems.length > 0) failures.push(...r.problems);
    dispositions = r.valid;
    console.log(`  ${doc.records.length} declared, ${r.valid.length} valid, ${r.problems.length} problem(s)`);
  } catch (e) {
    failures.push(`legal dispositions could not be loaded: ${e instanceof Error ? e.message : e}`);
  }

  // An unresolved finding with no covering disposition BLOCKS.
  const covered = new Set(dispositions.map((d) => `${d.target}|${d.purl}|${d.issue}`));
  const uncovered = allUnresolved.filter((u) => !covered.has(unresolvedScopeKey(u)));
  for (const u of uncovered) {
    failures.push(`C17 unresolved licence finding with no legal disposition: ${u.target} ${u.purl} (${u.issue}: ${u.detail})`);
  }

  // 4. Artifacts.
  const facts = {
    generated_from: { source_sha: headSha, as_of: args.asOf },
    schema: compiled.ok ? compiled.versions : null,
    sboms: sbomResults,
    targets: Object.fromEntries(TARGETS.map((t) => [t, {
      classified: inventories[t].components.length,
      unresolved: inventories[t].unresolved.length,
      components: inventories[t].components,
    }])),
  };
  const obligations = {
    $comment: 'MECHANICALLY DERIVED from the code-owned obligation table. Not legal advice.',
    obligation_table: OBLIGATION_TABLE,
    category_obligations: CATEGORY_OBLIGATIONS,
    targets: Object.fromEntries(TARGETS.map((t) => {
      const byCat = {};
      for (const c of inventories[t].components) {
        byCat[c.obligation_category] = (byCat[c.obligation_category] ?? 0) + 1;
      }
      return [t, {
        by_category: byCat,
        requires_notice: inventories[t].components.filter((c) => c.requires_notice).length,
        requires_source_offer: inventories[t].components.filter((c) => c.requires_source_offer).length,
        requires_modification_notice: inventories[t].components.filter((c) => c.requires_modification_notice).length,
        alternative_licences: inventories[t].components.filter((c) => c.alternative_licences).length,
      }];
    })),
  };
  const reconciliation = {
    generated_from: { source_sha: headSha, as_of: args.asOf },
    layers: {
      detected_facts: 'license-inventory.json — declared fields, manifest and file digests, copyright lines',
      mechanical_obligations: 'license-obligations.json — the code-owned table applied to those facts',
      reviewed_dispositions: 'scripts/gate/legal-dispositions.json — human decisions, separately governed',
      unresolved: 'listed below; these BLOCK the gate until disposed of',
    },
    targets: Object.fromEntries(TARGETS.map((t) => [t, {
      closure_components: derived.closures[t].nodes.size,
      inventory_classified: inventories[t].components.length,
      inventory_unresolved: inventories[t].unresolved.length,
      reconciliation_problems: reconcileInventory({ target: t, inventory: inventories[t], closure: derived.closures[t] }),
    }])),
    unresolved: allUnresolved.map((u) => ({
      target: u.target, purl: u.purl, version: u.version, issue: u.issue, detail: u.detail,
    })),
    dispositions: dispositions.map((d) => ({ id: d.id, target: d.target, purl: d.purl, classification: d.classification })),
  };

  const written = [
    write('license-inventory.json', canonicalJson(facts)),
    write('license-obligations.json', canonicalJson(obligations)),
    write('license-reconciliation.json', canonicalJson(reconciliation)),
    write('THIRD_PARTY_NOTICES.md', noticesMarkdown({ inventories, dispositions })),
  ];

  const manifest = {
    result: failures.length === 0 ? 'PASS' : 'FAIL',
    generated_from: { source_sha: headSha, as_of: args.asOf },
    schema: compiled.ok ? compiled.versions : null,
    sboms: sbomResults,
    artifacts: written,
    failures,
  };
  writeFileSync(join(args.outDir, 'c17-manifest.json'), canonicalJson(manifest));
  writeFileSync(join(args.outDir, failures.length === 0 ? 'RESULT-PASS.txt' : 'RESULT-FAIL.txt'),
    `C17 ${manifest.result} at ${headSha}\n`);

  console.log('\nartifacts:');
  for (const a of written) console.log(`  ${a.path} ${a.bytes}B ${a.sha256.slice(0, 16)}…`);
  if (failures.length > 0) {
    console.error('\n=== C17 GATE FAILED ===');
    for (const f of failures.slice(0, 40)) console.error(`  ${f}`);
    if (failures.length > 40) console.error(`  … and ${failures.length - 40} more`);
    process.exit(1);
  }
  console.log('\nC17 licence + schema gate: PASS');
}

try {
  main();
} catch (e) {
  console.error('=== C17 GATE FAILED (uncaught) ===');
  console.error(`  ${e instanceof Error ? e.stack : e}`);
  process.exit(1);
}
