#!/usr/bin/env node
/**
 * C17 GATE — official schema validation + licence inventory, obligations and notices.
 *
 * Fails closed on every step: schema preflight, compilation, validation, inventory build,
 * bidirectional reconciliation, disposition governance, artifact write. Nothing is downloaded.
 *
 * Usage: node scripts/gate/licence-obligations.mjs --out <DIR> [--as-of YYYY-MM-DD]
 *                                                  [--expected-sha <SHA>]
 */
import { writeFileSync, mkdirSync, readFileSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, dirname, relative, resolve, isAbsolute } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

import { deriveC16Expectation } from './generate-closures.mjs';
import { compileBomValidator, validateBom, VENDOR_DIR } from './lib/cyclonedx-schema.mjs';
import { buildTargetInventory, reconcileInventory, OBLIGATION_TABLE, CATEGORY_OBLIGATIONS } from './lib/license-closure.mjs';
import { loadCanonicalTexts, SPDX_TEXT_PROVENANCE } from './lib/licence-texts.mjs';
import { verifyBundledComponents } from './lib/bundled-components.mjs';
import {
  loadLegalDispositions, validateLegalDispositions, unresolvedScopeKey,
} from './lib/legal-dispositions.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const TARGETS = Object.freeze(['production', 'development']);
const sha256 = (b) => createHash('sha256').update(b).digest('hex');

/** Deterministic JSON: sorted keys, stable separators, no timestamps anywhere. */
function canonicalJson(value) {
  const walk = (v) => {
    if (Array.isArray(v)) return v.map(walk);
    if (v !== null && typeof v === 'object') {
      return Object.fromEntries(Object.keys(v).sort().map((k) => [k, walk(v[k])]));
    }
    return v;
  };
  return `${JSON.stringify(walk(value), null, 2)}\n`;
}

function parseArgs(argv) {
  const out = { outDir: null, asOf: null, expectedSha: null, final: false };
  for (let i = 0; i < argv.length; i += 1) {
    const a = argv[i];
    const next = () => {
      const v = argv[i + 1];
      if (v === undefined || v.startsWith('--')) throw new Error(`${a} requires a value`);
      i += 1;
      return v;
    };
    if (a === '--out') out.outDir = next();
    else if (a === '--as-of') out.asOf = next();
    else if (a === '--expected-sha') out.expectedSha = next();
    else if (a === '--final') out.final = true;
    else throw new Error(`unknown argument ${JSON.stringify(a)}`);
  }
  if (out.outDir === null) throw new Error('--out <DIR> is required');
  if (out.asOf === null) out.asOf = new Date().toISOString().slice(0, 10);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(out.asOf)) throw new Error('--as-of must be YYYY-MM-DD');
  // C17.2 B: --final is a POSTURE, and a posture with no subject is meaningless.
  if (out.final && out.expectedSha === null) {
    throw new Error('--final requires --expected-sha: a final run must name the source it claims to describe');
  }
  return out;
}

/**
 * C17.1 C — the notices file is a DELIVERABLE, not a summary.
 *
 * The C17 version truncated: `.slice(0, 8)` on the copyright lines a file carried and
 * `.slice(0, 3)` on the ones it printed, so `serve-static@2.2.1` lost Douglas Christopher Wilson
 * and three of its four holders never appeared. It printed "the canonical text must be
 * reproduced" and reproduced nothing, and "source must be offered" and offered nothing. A
 * notices file that states an obligation instead of discharging it is not a notices file.
 *
 * Now: every copyright line, every notice-required package's COMPLETE licence text (its own
 * shipped bytes where it has them, the pinned canonical SPDX text where it does not, each bound
 * by digest), named attribution for attribution licences, explicit modification statements, and
 * the concrete source-offer records. Nothing is elided.
 */
function noticesMarkdown({ inventories, dispositions, texts, sourceOffers, provenance, emitted = new Set() }) {
  const L = [];
  L.push('# Third-party notices', '');
  L.push('This file is GENERATED by `scripts/gate/licence-obligations.mjs` from the lockfile-derived');
  L.push('C16 target closures joined with the packages materialized by a frozen install. It is not');
  L.push('legal advice. It records what each package DECLARES, what its licence mechanically');
  L.push('requires, and the material needed to satisfy those requirements. It does not decide');
  L.push('whether any particular distribution is compliant.', '');
  L.push('Licence text comes from one of two places, stated per package: the bytes the package');
  L.push('itself ships, or the canonical SPDX text vendored at');
  L.push(`\`${provenance.repository}\` tag \`${provenance.release_tag}\`, commit`);
  L.push(`\`${provenance.commit}\`. Every text is bound by SHA-256 below.`, '');

  for (const target of TARGETS) {
    const inv = inventories[target];
    const third = inv.components.filter((c) => !c.first_party);
    const firstParty = inv.components.filter((c) => c.first_party);
    L.push(`## Target: ${target}`, '');
    L.push(`${third.length} third-party components. ${firstParty.length} first-party workspace`);
    L.push('packages are not published and carry no third-party obligation:');
    for (const c of firstParty) L.push(`* \`${c.purl}\``);
    L.push('');

    const byLicence = new Map();
    for (const c of third) {
      if (!byLicence.has(c.declared_license)) byLicence.set(c.declared_license, []);
      byLicence.get(c.declared_license).push(c);
    }
    for (const licence of [...byLicence.keys()].sort()) {
      const cs = byLicence.get(licence).sort((a, b) => (a.purl < b.purl ? -1 : 1));
      L.push(`### ${licence} — ${cs.length} component(s)`, '');
      for (const cat of [...new Set(cs.map((c) => c.obligation_category))].sort()) {
        for (const o of CATEGORY_OBLIGATIONS[cat] ?? []) L.push(`* ${o}`);
      }
      L.push('');
      for (const c of cs) {
        L.push(`#### \`${c.purl}\``, '');
        L.push(`* version: \`${c.version}\``);
        L.push(`* declared licence: \`${c.declared_license}\``);
        if (c.spdx_exceptions?.length > 0) L.push(`* licence exception(s): \`${c.spdx_exceptions.join(', ')}\``);
        L.push(`* package manifest sha256: \`${c.manifest_sha256}\``);
        // EVERY copyright line the package carries. No truncation.
        const copyright = c.copyright ?? [];
        if (copyright.length > 0) {
          L.push('* copyright:');
          for (const line of copyright) L.push(`  * ${line}`);
        }
        // Named attribution, required outright for attribution licences.
        if (c.obligation_category === 'attribution' || c.attribution?.author !== null) {
          const a = c.attribution ?? {};
          if (a.author) L.push(`* author: ${a.author}`);
          for (const co of a.contributors ?? []) L.push(`* contributor: ${co}`);
          if (a.repository) L.push(`* source: ${a.repository}`);
        }
        if (c.obligation_category === 'attribution' && !c.attribution?.author) {
          L.push('* **ATTRIBUTION PARTY NOT RECORDED — this is an unresolved obligation.**');
        }
        // Modification statement, stated rather than left as a placeholder.
        if (c.requires_modification_notice) {
          L.push('* modification: this project distributes the package UNMODIFIED, at the exact');
          L.push('  version the lockfile pins. No licensed file has been changed.');
        }
        // Source offer, concrete.
        if (c.requires_source_offer) {
          const offer = sourceOffers.get(c.purl);
          if (offer === undefined) {
            L.push('* **SOURCE OFFER MISSING — this is an unresolved obligation.**');
          } else {
            L.push(`* source offer: \`${offer.id}\` — corresponding source at`);
            L.push(`  ${offer.corresponding_source.upstream_repository} at \`${offer.corresponding_source.build_recipe_tag}\``);
            for (const step of offer.corresponding_source.obtain) L.push(`  * ${step}`);
            L.push(`* ${offer.modification_statement}`);
          }
        }
        // C17.2 D+E — EVERY discovered legal file is emitted, in full, with its kind.
        //
        // C17.1 emitted only files whose name began LICENSE/COPYING/NOTICE, so AUTHORS files were
        // collected and silently dropped, and third-party notices and bundled sidecars were never
        // discovered at all. Emission is now driven by the discovered set itself, which is what
        // makes discover -> inventory -> notices reconcilable.
        const emitFile = (f) => {
          const where = f.nested === true ? 'bundled, as shipped' : 'as shipped';
          L.push('', `<details><summary>${c.name} — ${f.file} [${f.kind}] (sha256 <code>${f.sha256}</code>, ${f.bytes} bytes, ${where})</summary>`, '', '```text');
          L.push(f.text.replace(/```/g, '`​``').trimEnd());
          L.push('```', '', '</details>', '');
          emitted.add(`${c.target}|${c.bom_ref}|${f.file}`);
        };
        for (const f of c.licence_files) emitFile(f);
        // Where the package ships no root licence of its own, the canonical SPDX text supplies
        // the notice obligation.
        if (c.requires_notice && !c.licence_files.some((f) => f.nested !== true && (f.kind === 'licence' || f.kind === 'copyright-notice'))) {
          for (const id of c.spdx_ids) {
            const t = texts.get(id);
            if (t === undefined) {
              L.push('', `* **CANONICAL TEXT FOR \`${id}\` UNAVAILABLE — unresolved obligation.**`, '');
              continue;
            }
            L.push('', `<details><summary>${c.name} — canonical ${id} text (sha256 <code>${t.sha256}</code>, ${t.bytes} bytes, from the pinned SPDX register)</summary>`, '', '```text');
            L.push(t.text.replace(/```/g, '`​``').trimEnd());
            L.push('```', '', '</details>', '');
          }
        }
        L.push('');
      }
    }
    if (inv.unresolved.length > 0) {
      L.push(`### Unresolved for ${target} — ${inv.unresolved.length}`, '');
      L.push('NOT classified. These require review; nothing here is asserted to be acceptable.', '');
      for (const u of inv.unresolved) L.push(`* \`${u.purl}\` — ${u.issue}: ${u.detail}`);
      L.push('');
    }
  }

  L.push('## Source-offer records', '');
  if (sourceOffers.size === 0) {
    L.push('None required.');
  } else {
    for (const o of [...sourceOffers.values()].sort((a, b) => (a.id < b.id ? -1 : 1))) {
      L.push(`### ${o.id} — \`${o.purl}\``, '');
      L.push(`* licence: \`${o.declared_license}\` (${o.obligation})`);
      for (const w of o.why) L.push(`* ${w}`);
      L.push(`* upstream: ${o.corresponding_source.upstream_repository} at \`${o.corresponding_source.build_recipe_tag}\``);
      for (const step of o.corresponding_source.obtain) L.push(`* ${step}`);
      for (const r of o.corresponding_source.relinking ?? []) L.push(`* ${r}`);
      L.push(`* ${o.modification_statement}`);
      for (const lim of o.limits) L.push(`* limit: ${lim}`);
      L.push('');
    }
  }

  L.push('## Reviewed legal dispositions', '');
  L.push(dispositions.length === 0
    ? 'None. No unresolved licence matter has been signed off; every unresolved item above remains open.'
    : dispositions.map((d) => `* ${d.id} — \`${d.purl}\` (${d.target}): ${d.classification}`).join('\n'));
  L.push('');
  return L.join('\n');
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  mkdirSync(args.outDir, { recursive: true });
  const failures = [];
  const write = (name, text) => {
    writeFileSync(join(args.outDir, name), text);
    return { path: name, bytes: Buffer.byteLength(text), sha256: sha256(text) };
  };

  console.log('=== C17 LICENCE + OFFICIAL SCHEMA GATE ===');
  const git = (...a) => spawnSync('git', a, { cwd: ROOT, encoding: 'utf8' });
  const headProbe = git('rev-parse', 'HEAD');
  const headSha = headProbe.stdout.trim();
  if (args.expectedSha !== null && headSha !== args.expectedSha) {
    failures.push(`HEAD is ${JSON.stringify(headSha)}, --expected-sha is ${args.expectedSha}`);
  }
  console.log(`source SHA:  ${headSha}`);
  console.log(`as-of date:  ${args.asOf}`);
  console.log(`mode:        ${args.final ? 'FINAL' : 'preliminary'}`);

  /**
   * C17.2 B — REAL final mode.
   *
   * C17 rejected `--final` as an unknown argument while the packager wrote `final_mode: true` into
   * every receipt regardless. The posture was therefore asserted by the packager about a run that
   * had never been asked to take it. `--final` now means something, and the packager derives the
   * posture from what this gate RECORDS rather than manufacturing it.
   */
  const finalPosture = {
    mode: args.final ? 'final' : 'preliminary',
    expected_sha: args.expectedSha,
    head_sha: headSha,
    worktree_clean_before: null,
    worktree_clean_after: null,
    output_outside_repo: null,
    target_materialization: null,
    test_seams: null,
  };
  if (args.final) {
    if (headProbe.status !== 0 || !/^[0-9a-f]{40}$/.test(headSha)) {
      failures.push('final mode requires a git checkout: HEAD could not be resolved');
    }
    const dirtyBefore = git('status', '--porcelain').stdout.trim();
    finalPosture.worktree_clean_before = dirtyBefore === '';
    if (dirtyBefore !== '') {
      failures.push(`final mode requires a clean worktree; ${dirtyBefore.split('\n').length} path(s) are modified`);
    }
    // Output must not be inside the repository: evidence written into the tree would itself
    // dirty the source it claims to describe.
    const rel = relative(ROOT, resolve(args.outDir));
    const inside = rel !== '' && !rel.startsWith('..') && !isAbsolute(rel);
    finalPosture.output_outside_repo = !inside;
    if (inside) {
      failures.push(`final mode requires --out OUTSIDE the repository; '${args.outDir}' resolves inside it`);
    }
    // The declared targets' platform-gated packages must be materialized, or the inventory is
    // describing a machine rather than a target.
    const missing = [];
    for (const probe of ['@img/sharp-libvips-linux-x64', '@next/swc-linux-x64-gnu']) {
      const enc = probe.replace(/\//g, '+');
      let found = false;
      try {
        found = readdirSync(join(ROOT, 'node_modules', '.pnpm')).some((e) => e.startsWith(`${enc}@`));
      } catch { found = false; }
      if (!found) missing.push(probe);
    }
    finalPosture.target_materialization = missing.length === 0;
    if (missing.length > 0) {
      failures.push(`final mode requires the declared linux-x64-glibc target to be materialized; missing ${missing.join(', ')}`);
    }
    // No test seam may be active.
    const seams = Object.keys(process.env).filter((k) => /^EYE_(GATE|SCANNER|SECRET|TEST)_/.test(k));
    finalPosture.test_seams = seams;
    if (seams.length > 0) {
      failures.push(`final mode refuses to run with test seams set: ${seams.join(', ')}`);
    }
  }

  // 1. Official schema, offline.
  const compiled = compileBomValidator(ROOT);
  if (!compiled.ok) failures.push(...compiled.problems);
  console.log(`\n-- official CycloneDX schema (${VENDOR_DIR}) --`);
  if (compiled.ok) {
    console.log(`  tag ${compiled.versions.schema_tag} commit ${compiled.versions.schema_commit}`);
    console.log(`  ajv ${compiled.versions.ajv} / ajv-formats ${compiled.versions.ajv_formats} / node ${compiled.versions.node}`);
  }

  const derived = deriveC16Expectation({ root: ROOT, asOfDate: args.asOf });
  const sbomResults = {};
  if (compiled.ok) {
    for (const target of TARGETS) {
      const text = derived.sbomTexts[target];
      const errs = validateBom(compiled.validate, JSON.parse(text), target);
      sbomResults[target] = { sha256: sha256(text), bytes: Buffer.byteLength(text), schema_errors: errs.length };
      if (errs.length > 0) failures.push(...errs);
      console.log(`  [${errs.length === 0 ? 'ok' : 'FAIL'}] ${target} sbom ${sha256(text).slice(0, 16)}… ${errs.length} schema error(s)`);
    }
  }

  // 2. Inventories from source + materialized packages.
  console.log('\n-- licence inventory --');
  const inventories = {};
  const allUnresolved = [];
  for (const target of TARGETS) {
    const inv = buildTargetInventory({ root: ROOT, target, closure: derived.closures[target] });
    const rec = reconcileInventory({ target, inventory: inv, closure: derived.closures[target] });
    if (rec.length > 0) failures.push(...rec);
    inventories[target] = inv;
    allUnresolved.push(...inv.unresolved);
    console.log(`  ${target}: ${inv.components.length} classified, ${inv.unresolved.length} unresolved, ${rec.length} reconciliation problem(s)`);
  }

  // 2b. Canonical licence texts and source offers — the material the notices must CARRY.
  console.log('\n-- canonical licence texts + source offers --');
  const textsResult = loadCanonicalTexts(ROOT);
  if (!textsResult.ok) failures.push(...textsResult.problems);
  const texts = textsResult.texts ?? new Map();
  console.log(`  ${texts.size} canonical text(s) verified against the code-owned provenance`);

  const sourceOffers = new Map();
  try {
    const offerDoc = JSON.parse(readFileSync(join(ROOT, 'scripts/gate/source-offers.json'), 'utf8'));
    if (offerDoc.schema_version !== '1.0.0') {
      failures.push(`C17 source-offers schema_version is ${JSON.stringify(offerDoc.schema_version)}, expected "1.0.0"`);
    }
    for (const r of offerDoc.records ?? []) {
      // A record must name a component the inventory actually contains, at that exact version.
      const match = TARGETS.some((t) => inventories[t].components.some(
        (c) => c.purl === r.purl && c.version === r.version,
      ));
      if (!match) {
        failures.push(`C17 source-offer ${r.id} names ${r.purl}@${r.version}, which no target inventory contains`);
        continue;
      }
      if (sourceOffers.has(r.purl)) {
        failures.push(`C17 source-offer ${r.id} duplicates the scope already covered for ${r.purl}`);
        continue;
      }
      for (const field of ['id', 'purl', 'declared_license', 'modification_statement', 'owner']) {
        if (typeof r[field] !== 'string' || r[field].trim() === '') {
          failures.push(`C17 source-offer ${r.id ?? '(unnamed)'} is missing '${field}'`);
        }
      }
      const cs = r.corresponding_source;
      if (cs === null || typeof cs !== 'object'
        || typeof cs.upstream_repository !== 'string'
        || typeof cs.build_recipe_tag !== 'string'
        || !Array.isArray(cs.obtain) || cs.obtain.length === 0) {
        failures.push(`C17 source-offer ${r.id} has no concrete corresponding_source`);
        continue;
      }
      sourceOffers.set(r.purl, r);
    }
  } catch (e) {
    failures.push(`C17 source-offers could not be loaded: ${e instanceof Error ? e.message : e}`);
  }
  console.log(`  ${sourceOffers.size} source-offer record(s) bound to real components`);

  // Every source-offer obligation must be DISCHARGED, not merely stated.
  for (const target of TARGETS) {
    for (const c of inventories[target].components) {
      if (c.requires_source_offer && !sourceOffers.has(c.purl)) {
        failures.push(`C17 ${target} ${c.purl} requires a source offer and none is recorded`);
      }
      if (c.obligation_category === 'attribution' && !c.attribution?.author) {
        failures.push(`C17 ${target} ${c.purl} is under an attribution licence with no recorded author`);
      }
      if (c.requires_notice) {
        const hasShipped = c.licence_files.some((f) => /^(LICEN[CS]E|COPYING)/i.test(f.file));
        const missing = hasShipped ? [] : c.spdx_ids.filter((id) => !texts.has(id));
        if (missing.length > 0) {
          failures.push(`C17 ${target} ${c.purl} requires a notice but no licence text is available for ${missing.join(', ')}`);
        }
      }
    }
  }

  // 2c. The BUNDLED native stack: ~30 libraries inside one shared object.
  console.log('\n-- bundled native stack (@img/sharp-libvips-linux-x64) --');
  const bundled = verifyBundledComponents(ROOT, { texts });
  if (!bundled.ok) failures.push(...bundled.problems);
  for (const n of bundled.notes) console.log(`  ${n}`);

  // 3. Legal dispositions — separate document, separate governance.
  console.log('\n-- legal dispositions --');
  const unresolvedKeys = new Set(allUnresolved.map(unresolvedScopeKey));
  let dispositions = [];
  try {
    const { doc } = loadLegalDispositions(ROOT);
    const r = validateLegalDispositions(doc, {
      runDate: args.asOf,
      root: ROOT,
      isTracked: (rel) => spawnSync('git', ['ls-files', '--error-unmatch', rel], { cwd: ROOT, encoding: 'utf8' }).status === 0,
      unresolvedKeys,
    });
    if (r.problems.length > 0) failures.push(...r.problems);
    dispositions = r.valid;
    console.log(`  ${doc.records.length} declared, ${r.valid.length} valid, ${r.problems.length} problem(s)`);
  } catch (e) {
    failures.push(`legal dispositions could not be loaded: ${e instanceof Error ? e.message : e}`);
  }

  // An unresolved finding with no covering disposition BLOCKS.
  const covered = new Set(dispositions.map((d) => `${d.target}|${d.purl}|${d.issue}`));
  const uncovered = allUnresolved.filter((u) => !covered.has(unresolvedScopeKey(u)));
  for (const u of uncovered) {
    failures.push(`C17 unresolved licence finding with no legal disposition: ${u.target} ${u.purl} (${u.issue}: ${u.detail})`);
  }

  // 4. Artifacts.
  const facts = {
    generated_from: { source_sha: headSha, as_of: args.asOf },
    schema: compiled.ok ? compiled.versions : null,
    sboms: sbomResults,
    targets: Object.fromEntries(TARGETS.map((t) => [t, {
      classified: inventories[t].components.length,
      unresolved: inventories[t].unresolved.length,
      components: inventories[t].components,
    }])),
  };
  const obligations = {
    $comment: 'MECHANICALLY DERIVED from the code-owned obligation table. Not legal advice.',
    obligation_table: OBLIGATION_TABLE,
    category_obligations: CATEGORY_OBLIGATIONS,
    targets: Object.fromEntries(TARGETS.map((t) => {
      const byCat = {};
      for (const c of inventories[t].components) {
        byCat[c.obligation_category] = (byCat[c.obligation_category] ?? 0) + 1;
      }
      return [t, {
        by_category: byCat,
        requires_notice: inventories[t].components.filter((c) => c.requires_notice).length,
        requires_source_offer: inventories[t].components.filter((c) => c.requires_source_offer).length,
        requires_modification_notice: inventories[t].components.filter((c) => c.requires_modification_notice).length,
        alternative_licences: inventories[t].components.filter((c) => c.alternative_licences).length,
      }];
    })),
  };
  const reconciliation = {
    generated_from: { source_sha: headSha, as_of: args.asOf },
    layers: {
      detected_facts: 'license-inventory.json — declared fields, manifest and file digests, copyright lines',
      mechanical_obligations: 'license-obligations.json — the code-owned table applied to those facts',
      reviewed_dispositions: 'scripts/gate/legal-dispositions.json — human decisions, separately governed',
      unresolved: 'listed below; these BLOCK the gate until disposed of',
    },
    targets: Object.fromEntries(TARGETS.map((t) => [t, {
      closure_components: derived.closures[t].nodes.size,
      inventory_classified: inventories[t].components.length,
      inventory_unresolved: inventories[t].unresolved.length,
      reconciliation_problems: reconcileInventory({ target: t, inventory: inventories[t], closure: derived.closures[t] }),
    }])),
    unresolved: allUnresolved.map((u) => ({
      target: u.target, purl: u.purl, version: u.version, issue: u.issue, detail: u.detail,
    })),
    dispositions: dispositions.map((d) => ({ id: d.id, target: d.target, purl: d.purl, classification: d.classification })),
  };

  // C17.2 D+E — DISCOVER -> INVENTORY -> NOTICES must be exact in both directions.
  const emitted = new Set();
  const noticesText = noticesMarkdown({
    inventories, dispositions, texts, sourceOffers, provenance: SPDX_TEXT_PROVENANCE, emitted,
  });
  const expectedLegal = new Set();
  for (const target of TARGETS) {
    for (const c of inventories[target].components) {
      for (const f of c.licence_files ?? []) {
        // Keyed on bom_ref, NOT purl: a PURL is not unique within a lockfile — ajv-formats@3.0.1
        // resolves twice against two different ajv peers — so a purl key would call the second
        // component's licence file a duplicate of the first's.
        const key = `${target}|${c.bom_ref}|${f.file}`;
        if (expectedLegal.has(key)) {
          failures.push(`C17 ${target} ${c.purl} lists the legal file '${f.file}' more than once`);
        }
        expectedLegal.add(key);
      }
    }
  }
  for (const key of expectedLegal) {
    if (!emitted.has(key)) failures.push(`C17 legal file NOT emitted in the notices bundle: ${key}`);
  }
  for (const key of emitted) {
    if (!expectedLegal.has(key)) failures.push(`C17 notices bundle emits an unknown legal file: ${key}`);
  }
  console.log(`  legal files: ${expectedLegal.size} discovered, ${emitted.size} emitted`);

  const written = [
    write('license-inventory.json', canonicalJson(facts)),
    write('license-obligations.json', canonicalJson(obligations)),
    write('license-reconciliation.json', canonicalJson(reconciliation)),
    write('THIRD_PARTY_NOTICES.md', noticesText),
    write('license-texts.json', canonicalJson({
      $comment: 'Canonical SPDX texts reproduced in the notices, bound by digest. Vendored and '
        + 'pinned; never fetched at generation time.',
      provenance: SPDX_TEXT_PROVENANCE,
      texts: Object.fromEntries([...texts.entries()].map(([id, t]) => [id, {
        file: t.file, url: t.url, bytes: t.bytes, sha256: t.sha256,
      }])),
    })),
    write('bundled-components.json', canonicalJson({
      $comment: 'The bundled native third-party stack of @img/sharp-libvips-linux-x64, reconciled '
        + 'against the versions.json and README.md the package itself ships. Not npm components, '
        + 'so deliberately not in the C16 SBOM; these are what the obligations attach to.',
      reconciled: bundled.ok,
      manifest: bundled.manifest ?? null,
    })),
    write('source-offers.json', canonicalJson({
      $comment: 'Source-offer records discharging weak-copyleft obligations. Each is bound to a '
        + 'component the inventory contains, at that exact version.',
      records: [...sourceOffers.values()],
    })),
  ];

  if (args.final) {
    const dirtyAfter = git('status', '--porcelain').stdout.trim();
    finalPosture.worktree_clean_after = dirtyAfter === '';
    if (dirtyAfter !== '') {
      failures.push(`final mode: generation DIRTIED the worktree (${dirtyAfter.split('\n').length} path(s))`);
    }
  }
  const manifest = {
    result: failures.length === 0 ? 'PASS' : 'FAIL',
    mode: finalPosture.mode,
    final_source_posture: finalPosture,
    generated_from: { source_sha: headSha, as_of: args.asOf },
    schema: compiled.ok ? compiled.versions : null,
    sboms: sbomResults,
    artifacts: written,
    failures,
  };
  writeFileSync(join(args.outDir, 'c17-manifest.json'), canonicalJson(manifest));
  writeFileSync(join(args.outDir, failures.length === 0 ? 'RESULT-PASS.txt' : 'RESULT-FAIL.txt'),
    `C17 ${manifest.result} at ${headSha}\n`);

  console.log('\nartifacts:');
  for (const a of written) console.log(`  ${a.path} ${a.bytes}B ${a.sha256.slice(0, 16)}…`);
  if (failures.length > 0) {
    console.error('\n=== C17 GATE FAILED ===');
    for (const f of failures.slice(0, 40)) console.error(`  ${f}`);
    if (failures.length > 40) console.error(`  … and ${failures.length - 40} more`);
    process.exit(1);
  }
  console.log('\nC17 licence + schema gate: PASS');
}

try {
  main();
} catch (e) {
  console.error('=== C17 GATE FAILED (uncaught) ===');
  console.error(`  ${e instanceof Error ? e.stack : e}`);
  process.exit(1);
}
