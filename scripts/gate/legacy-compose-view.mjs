#!/usr/bin/env node
/**
 * The LEGACY VIEW of docker-compose.yml — the service pins as the frozen C18 verifiers read them.
 *
 * WHY THIS EXISTS. Every byte-frozen C18 differential predecessor under
 * apps/api/test/gate/fixtures/c18-legacy-<sha>/c18-db-paths.mjs derives ROOT from its own
 * location and reads `apps/api/test/gate/docker-compose.yml` with
 *
 *     /image:\s*(postgres@sha256:[0-9a-f]{64})/      /image:\s*(redis@sha256:[0-9a-f]{64})/
 *
 * — the spelling the compose file had when each of them was frozen. On 2026-09-10 the live file
 * was re-pinned to REGISTRY-PATH references (ghcr.io/<owner>/<repo>/<service>@sha256:<digest>),
 * which that pattern cannot read, so every frozen verifier threw before judging anything and each
 * non-vacuity and differential control failed for a reason that has nothing to do with what it
 * measures. The fixtures are frozen and are never edited; the seam they read through was a symlink
 * to the live file and is now this tracked, GENERATED view.
 *
 * WHAT THE VIEW IS. The live docker-compose.yml verbatim, except that for each service named in
 * LEGACY_SERVICES the `image:` reference `<registry path>/<service>@sha256:<digest>` is spelled
 * `<service>@sha256:<digest>` — the SAME digest under the pre-registry name. Nothing else changes:
 * a diff of the view against the live file shows the generated header and the two image lines.
 *
 * ONE MAPPING, TWO CONSUMERS. `legacyImageMapping()` derives { <live reference> → <legacy
 * reference> } from the live file. The generator applies it to the compose text; the suite's era
 * downgrade (apps/api/test/gate/c18-mutation-controls.suite.ts, `legacyImageView`) applies the
 * same mapping to the ledger of the genuine archive — every argv element and every manifest or
 * receipt field that IS a live reference — so a frozen verifier's compose-vs-ledger comparison
 * holds exactly. No digest is written anywhere but the live compose file.
 *
 * STALENESS IS A FAILURE. `--check` exits 1 when the tracked view is not what the live file
 * renders to; CI runs it (blocking) immediately before the C18 gate, and the unit test in
 * apps/api/test/gate/c18-db-paths.test.ts asserts the same thing plus digest equality.
 *
 * The CURRENT verifier (scripts/gate/c18-db-paths.mjs, scripts/gate/lib/c18-query-plan.mjs) keeps
 * reading the live file by service identity and judging the genuine registry references; nothing
 * here changes what it accepts.
 *
 *   node scripts/gate/legacy-compose-view.mjs             # (re)generate the tracked view
 *   node scripts/gate/legacy-compose-view.mjs --check     # exit 1 when the tracked view is stale
 *   … [--live <compose file>] [--view <view file>]        # other paths (tests)
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const LIVE_COMPOSE = join(ROOT, 'docker-compose.yml');
export const LEGACY_VIEW = join(ROOT, 'apps', 'api', 'test', 'gate', 'docker-compose.yml');
/** The services the frozen verifiers pin by name; their order is the order of the view header. */
export const LEGACY_SERVICES = Object.freeze(['postgres', 'redis']);

/** A digest-pinned reference: `<name>@sha256:<64 lowercase hex>`, the name possibly registry-pathed. */
const DIGEST_REF = /^([a-z0-9][a-z0-9._/-]*)@(sha256:[0-9a-f]{64})$/;
const IMAGE_LINE = /^\s{4}image:\s*([a-z0-9][a-z0-9._/-]*@sha256:[0-9a-f]{64})\b/m;

/** The header the generated view carries. It must never contain an `image:` key. */
export const VIEW_HEADER = [
  '# GENERATED by scripts/gate/legacy-compose-view.mjs from docker-compose.yml — DO NOT EDIT.',
  '# This is the legacy view of the live compose file for the byte-frozen C18 differential',
  '# verifiers (apps/api/test/gate/fixtures/c18-legacy-*), which predate registry-path pins and',
  '# read each service pin as `<service>@sha256:<digest>`. It carries the SAME digests as the live',
  '# file; only the service image references are respelled, everything else is verbatim.',
  '#   regenerate:  node scripts/gate/legacy-compose-view.mjs',
  '#   stale-check: node scripts/gate/legacy-compose-view.mjs --check   (CI, before the C18 gate)',
  '',
].join('\n');

/** The text of one top-level service block (its indented body), or '' when the service is absent. */
function serviceBlock(text, service) {
  return new RegExp(`^  ${service}:\\n((?:    .*\\n|\\n)*)`, 'm').exec(text)?.[1] ?? '';
}

/**
 * Each legacy service's live `image:` reference, read by SERVICE identity exactly as the current
 * verifier reads it. Throws when a service is missing or not digest-pinned: the view has no
 * meaning for a compose file the frozen verifiers could not have judged either.
 */
export function serviceImages(text) {
  const images = {};
  for (const service of LEGACY_SERVICES) {
    const ref = IMAGE_LINE.exec(serviceBlock(text, service))?.[1];
    if (ref === undefined) throw new Error(`docker-compose.yml does not pin the ${service} image by digest`);
    images[service] = ref;
  }
  return images;
}

/**
 * The legacy spelling of a live reference: `<service>@sha256:<digest>`. The reference must be
 * digest-pinned and its name's last path segment must BE the service, so the mapping can only
 * rename a registry path away — never relabel a foreign image as the service.
 */
export function legacyImageRef(service, liveRef) {
  const m = DIGEST_REF.exec(String(liveRef));
  if (m === null) throw new Error(`${service}: ${JSON.stringify(liveRef)} is not a digest-pinned reference`);
  const name = m[1].split('/').pop();
  if (name !== service) throw new Error(`${service}: ${JSON.stringify(liveRef)} does not name the ${service} image`);
  return `${service}@${m[2]}`;
}

/** { <live reference> → <legacy reference> } for every legacy service, derived from the live text. */
export function legacyImageMapping(text = readFileSync(LIVE_COMPOSE, 'utf8')) {
  const mapping = new Map();
  for (const [service, ref] of Object.entries(serviceImages(text))) mapping.set(ref, legacyImageRef(service, ref));
  return mapping;
}

/** The view rendered from the live text: header, then the live text with each service's image line respelled. */
export function renderLegacyView(text) {
  let out = text;
  for (const [service, ref] of Object.entries(serviceImages(text))) {
    const legacy = legacyImageRef(service, ref);
    const head = new RegExp(`^  ${service}:\\n`, 'm').exec(out);
    const block = serviceBlock(out, service);
    const start = head.index + head[0].length;
    const line = IMAGE_LINE.exec(block);
    const respelled = `${block.slice(0, line.index)}${line[0].replace(ref, legacy)}${block.slice(line.index + line[0].length)}`;
    out = `${out.slice(0, start)}${respelled}${out.slice(start + block.length)}`;
  }
  if (/^\s*image:/m.test(VIEW_HEADER)) throw new Error('the view header must not carry an image: key');
  return `${VIEW_HEADER}${out}`;
}

/**
 * Whether a view's text is exactly what the live text renders to. Returns { ok, expected, problems }.
 * A missing view is stale; a byte difference is stale — the frozen readers read bytes.
 */
export function checkLegacyView({ liveText, viewText }) {
  const expected = renderLegacyView(liveText);
  const problems = [];
  if (viewText === null) problems.push('the legacy view does not exist');
  else if (viewText !== expected) problems.push('the legacy view is stale: it is not what the live docker-compose.yml renders to');
  return { ok: problems.length === 0, expected, problems };
}

export function isMainModule(argv1, url) {
  try { return typeof argv1 === 'string' && argv1.length > 0 && fileURLToPath(url) === argv1; } catch { return false; }
}

function main(args) {
  const opt = (name) => { const i = args.indexOf(name); return i === -1 ? null : args[i + 1] ?? null; };
  const live = opt('--live') ?? LIVE_COMPOSE;
  const view = opt('--view') ?? LEGACY_VIEW;
  const liveText = readFileSync(live, 'utf8');
  const rel = (p) => relative(ROOT, p) || p;
  if (args.includes('--check')) {
    const viewText = existsSync(view) ? readFileSync(view, 'utf8') : null;
    const r = checkLegacyView({ liveText, viewText });
    if (!r.ok) {
      for (const p of r.problems) process.stderr.write(`legacy-compose-view: ${p} (${rel(view)})\n`);
      process.stderr.write('legacy-compose-view: regenerate with `node scripts/gate/legacy-compose-view.mjs` and commit the result\n');
      return 1;
    }
    const digests = [...legacyImageMapping(liveText).values()].join(', ');
    process.stdout.write(`legacy-compose-view: ${rel(view)} is current (${digests})\n`);
    return 0;
  }
  writeFileSync(view, renderLegacyView(liveText));
  process.stdout.write(`legacy-compose-view: wrote ${rel(view)} from ${rel(live)}\n`);
  return 0;
}

if (isMainModule(process.argv[1], import.meta.url)) process.exit(main(process.argv.slice(2)));
