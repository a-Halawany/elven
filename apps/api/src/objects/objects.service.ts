/**
 * Canonical object service — CP-OBJ-01 (ADR-P0-05/06/07, remediation R5).
 * Create / version / correct / as-of retrieval. Every production write
 * validates the COMPLETE 43-field header against the contracts schema;
 * content_digest binds all 43 registry fields + payload via one JCS
 * representation (canonicalHeaderDigest); the write re-reads the stored row,
 * rebuilds the header, and re-verifies the digest INSIDE the same transaction
 * (storage round-trip verification — a lossy mapping aborts the write).
 * Payload validated against the registered object-type schema; writes without
 * minimum provenance rejected (EYE-PRV-001); versions are immutable and
 * content-addressed; corrections are non-destructive new versions linked via
 * correction_of.
 */
import { HttpException, Injectable } from '@nestjs/common';
import { Ajv2020 } from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import {
  canonicalHeaderDigest,
  errorBody,
  hasMinimumProvenance,
  isTruthState,
  validateHeader,
  type CanonicalHeader,
  type TimeAxis,
  type TimeValue,
  type TruthState,
} from '@eye/contracts';
import type { ObjectReads, ObjectWrites } from '../shared/capabilities.js';
import { newId } from '../shared/ids.js';
import type { ScopeContext } from '../shared/scope.js';
/* B50 hd */
import { buildHeader, HeaderBuildError, rebuildHeaderFromRow as rebuildFromRow, timeDeclaration } from './header-builder.js';
/* end B50 hd */

export interface CreateObjectInput {
  objectType: string;
  truthState: string;
  syntheticState?: boolean;
  eventTime?: string | null;
  observationTime?: string | null;
  validFrom?: string | null;
  validTo?: string | null;
  timePrecision?: string;
  sourceClockQuality?: 'trusted' | 'degraded' | 'unknown';
  evidenceRefs?: string[];
  methodRef?: string | null;
  humanRefs?: string[];
  sourceObjectIds?: string[];
  classification: string;
  purposeScope: string;
  schemaVersion?: string;
  payload: Record<string, unknown>;
  /* B50 hd: a stated time per axis (ES-26-004) — its header instant and precision are placed, and the full value is recorded in
     objects.time_qualifiers by the admission (0120 §HD.4). */
  time?: Partial<Record<TimeAxis, TimeValue>>;
  /* end B50 hd */
}

export interface ObjectRow {
  object_id: string;
  object_type: string;
  object_version: string | number;
  truth_state: string;
  lifecycle_state: string;
  recorded_at: Date;
  content_digest: string;
  [k: string]: unknown;
}

const ajv = new Ajv2020({ allErrors: true, strict: false });
// eslint-disable-next-line @typescript-eslint/no-unsafe-call, @typescript-eslint/no-unsafe-member-access
(addFormats as unknown as { default?: (a: Ajv2020) => void }).default?.(ajv) ??
  (addFormats as unknown as (a: Ajv2020) => void)(ajv);

function bad(code: 'EYE_REQ_001' | 'EYE_PRV_001' | 'EYE_TMP_001' | 'EYE_STA_001' | 'EYE_STA_002' | 'EYE_STA_003', corr: string, msg: string, status = 422): HttpException {
  return new HttpException(errorBody(code, corr, msg), status);
}

@Injectable()
export class ObjectsService {
  /** Validate + admit version 1 of a canonical object (step 5 + 6 of the commit path). */
  async createObject(
    cap: ObjectWrites,
    ctx: ScopeContext,
    actor: string,
    correlationId: string,
    input: CreateObjectInput,
    /** Gate-2.2 C6: generated by the route BEFORE the capability is minted. */
    objectId: string,
  ): Promise<ObjectRow> {
    return this.insertVersion(cap, ctx, actor, correlationId, input, {
      objectId,
      version: 1,
      correctionOf: null,
      lifecycle: 'admitted',
    });
  }

  /** Non-destructive correction: new version linked via correction_of (ADR-0005, DADR-007). */
  async correctObject(
    cap: ObjectWrites,
    ctx: ScopeContext,
    actor: string,
    correlationId: string,
    objectId: string,
    expectedVersion: number,
    input: CreateObjectInput,
  ): Promise<ObjectRow> {
    const latest = (await cap
      .readCanonicalObjects()
      .select(['object_id', 'object_version', 'object_type'])
      .where('object_id' as never, '=', objectId as never)
      .orderBy('object_version' as never, 'desc')
      .limit(1)
      .executeTakeFirst()) as { object_id: string; object_version: string | number; object_type: string } | undefined;
    if (latest === undefined) throw bad('EYE_STA_001', correlationId, 'no authorized object version matches', 404);
    const latestVersion = Number(latest.object_version);
    if (latestVersion !== expectedVersion) {
      throw bad('EYE_STA_002', correlationId, `expected version ${expectedVersion}, authoritative is ${latestVersion}`, 409);
    }
    if (latest.object_type !== input.objectType) {
      throw bad('EYE_REQ_001', correlationId, 'object type cannot change across versions', 400);
    }
    return this.insertVersion(cap, ctx, actor, correlationId, input, {
      objectId,
      version: latestVersion + 1,
      correctionOf: `${objectId}@${latestVersion}`,
      lifecycle: 'corrected',
    });
  }

  /** Current view (latest version per object). */
  async getCurrent(cap: ObjectReads, objectId: string, correlationId: string): Promise<ObjectRow> {
    const row = (await cap
      .readCanonicalObjects()
      .selectAll()
      .where('object_id' as never, '=', objectId as never)
      .orderBy('object_version' as never, 'desc')
      .limit(1)
      .executeTakeFirst()) as ObjectRow | undefined;
    if (row === undefined) throw bad('EYE_STA_001', correlationId, 'no authorized object version matches', 404);
    return servedRow(row);
  }

  /**
   * As-of (known-at) retrieval — the state of knowledge at record time T,
   * without hindsight contamination (C-011): the latest version whose
   * recorded_at <= T; later corrections are invisible.
   */
  async getKnownAt(cap: ObjectReads, objectId: string, knownAt: string, correlationId: string): Promise<ObjectRow> {
    const t = new Date(knownAt);
    if (Number.isNaN(t.getTime())) throw bad('EYE_TMP_001', correlationId, 'invalid known-at instant', 400);
    const row = (await cap
      .readCanonicalObjects()
      .selectAll()
      .where('object_id' as never, '=', objectId as never)
      .where('recorded_at', '<=', t)
      .orderBy('object_version' as never, 'desc')
      .limit(1)
      .executeTakeFirst()) as ObjectRow | undefined;
    if (row === undefined) {
      throw bad('EYE_STA_001', correlationId, 'object was not known at the requested instant', 404);
    }
    return servedRow(row);
  }

  async listObjects(cap: ObjectReads, objectType: string | null, limit: number): Promise<ObjectRow[]> {
    let q = cap
      .readCanonicalObjects()
      .selectAll()
      .orderBy('recorded_at' as never, 'desc')
      .limit(Math.min(limit, 200));
    if (objectType !== null) q = q.where('object_type' as never, '=', objectType as never);
    return ((await q.execute()) as ObjectRow[]).map(servedRow);
  }

  async versionHistory(cap: ObjectReads, objectId: string): Promise<ObjectRow[]> {
    return ((await cap
      .readCanonicalObjects()
      .selectAll()
      .where('object_id' as never, '=', objectId as never)
      .orderBy('object_version' as never)
      .execute()) as ObjectRow[]).map(servedRow);
  }

  /* B50 hd (0120 §HD) — THE HEADER'S SIDE: per version, the operation and header basis (objects.version_operations) and the time
     qualifiers (objects.time_qualifiers); a version without them was recorded before B50 and reads so; and the object's identity declaration. */
  async headerOf(cap: ObjectReads, objectId: string, correlationId: string): Promise<Record<string, unknown>> {
    const versions = (await cap.readCanonicalObjects().select(['object_id', 'object_type', 'object_version', 'recorded_at', 'lifecycle_state'])
      .where('object_id' as never, '=', objectId as never).orderBy('object_version' as never).execute()) as Array<Record<string, unknown>>;
    if (versions.length === 0) throw bad('EYE_STA_001', correlationId, 'no authorized object version matches', 404);
    const ops = (await cap.readVersionOperations().selectAll().where('object_id' as never, '=', objectId as never).execute()) as Array<Record<string, unknown>>;
    const tqs = (await cap.readTimeQualifiers().selectAll().where('object_id' as never, '=', objectId as never).orderBy('axis' as never).execute()) as Array<Record<string, unknown>>;
    const type = String(versions[0]?.['object_type']);
    return {
      objectId, objectType: type,
      identity: await cap.identityDeclaration(type, objectId),
      versions: versions.map((v) => {
        const n = Number(v['object_version']);
        const op = ops.find((o) => Number(o['object_version']) === n) ?? null;
        return {
          version: n, recordedAt: v['recorded_at'], lifecycleState: v['lifecycle_state'],
          header: op === null ? 'recorded before B50 — not populated' : 'stated',
          operation: op === null ? null : {
            operationId: op['operation_id'], boundAction: op['bound_action'], idempotencyKey: op['idempotency_key'], idempotencyBasis: op['idempotency_basis'],
            traceId: op['trace_id'], traceSource: op['trace_source'], basis: op['header_basis'],
          },
          time: tqs.filter((t) => Number(t['object_version']) === n).map((t) => ({
            axis: t['axis'], kind: t['kind'], instant: t['instant'], earliest: t['earliest'], latest: t['latest'], precision: t['time_precision'],
            zone: t['zone'], source: t['source'], rule: t['rule'], conflicts: t['conflicts'], clockQuality: t['clock_quality'], declared: t['declared'],
          })),
        };
      }),
    };
  }

  async headerProfiles(cap: ObjectReads): Promise<Array<Record<string, unknown>>> {
    return (await cap.readHeaderProfiles().selectAll().where('state' as never, '=', 'active' as never)
      .orderBy('object_type' as never).orderBy('profile_version' as never, 'desc').execute()) as Array<Record<string, unknown>>;
  }

  async layerContracts(cap: ObjectReads): Promise<Array<Record<string, unknown>>> {
    return cap.layerContracts();
  }
  /* end B50 hd */

  // ===== internals =====

  private async insertVersion(
    cap: ObjectWrites,
    ctx: ScopeContext,
    actor: string,
    correlationId: string,
    input: CreateObjectInput,
    v: { objectId: string; version: number; correctionOf: string | null; lifecycle: string },
  ): Promise<ObjectRow> {
    // Truth-state enum (ADR-P0-06) — canonical nine values only.
    if (!isTruthState(input.truthState)) {
      throw bad('EYE_STA_003', correlationId, `"${input.truthState}" is not a canonical truth state`, 422);
    }
    const truthState = input.truthState as TruthState;
    const syntheticState = input.syntheticState ?? (truthState === 'synthetic');
    if (truthState === 'synthetic' && !syntheticState) {
      throw bad('EYE_STA_003', correlationId, 'synthetic truth state requires synthetic_state marker', 422);
    }

    // Minimum provenance (acceptance criterion 7).
    const prov = {
      evidence_refs: input.evidenceRefs ?? [],
      source_object_ids: input.sourceObjectIds ?? [],
      method_ref: input.methodRef ?? null,
      human_refs: input.humanRefs ?? [],
    };
    if (!hasMinimumProvenance(prov)) {
      throw bad('EYE_PRV_001', correlationId, 'write rejected: no evidence/source/method/human provenance supplied');
    }

    // Temporal sanity (four-axis model). DB CHECK valid_interval_order mirrors this.
    if (input.validTo != null && input.validFrom == null) {
      throw bad('EYE_TMP_001', correlationId, 'valid_to requires valid_from', 400);
    }
    if (input.validTo != null && input.validFrom != null && new Date(input.validTo) <= new Date(input.validFrom)) {
      throw bad('EYE_TMP_001', correlationId, 'valid_to must be after valid_from', 400);
    }

    // Payload schema from the registry.
    const schemaVersion = input.schemaVersion ?? 'v1';
    const reg = (await cap
      .readSchemaRegistry()
      .select(['json_schema'])
      .where('object_type' as never, '=', input.objectType as never)
      .where('schema_version' as never, '=', schemaVersion as never)
      .executeTakeFirst()) as { json_schema: Record<string, unknown> } | undefined;
    if (reg === undefined) {
      throw bad('EYE_REQ_001', correlationId, `no registered schema ${input.objectType}@${schemaVersion}`, 400);
    }
    const validate = ajv.compile(reg.json_schema);
    if (!validate(input.payload)) {
      const detail = (validate.errors ?? []).map((e) => `${e.instancePath || '/'} ${e.message ?? ''}`).join('; ');
      throw bad('EYE_REQ_001', correlationId, `payload schema violation: ${detail}`, 400);
    }

    // Timestamps are normalized to ISO-8601 UTC (ms precision) so the header,
    // the stored row, and the round-trip rebuild share one representation.
    const iso = (s: string | null | undefined): string | null => (s == null ? null : new Date(s).toISOString());
    const recordedAt = new Date();

    // The COMPLETE 43-field header (R5) — validated as a whole on every
    // production write, then digest-bound in its entirety.
    // B50 hd: the shared header builder (header-builder.ts) — the complete 43-field header, with what the writer does not state STATED
    // (declared absences, ontology:none, the type's quality profile); validated as a whole below, then digest-bound in its entirety.
    let header: CanonicalHeader;
    try {
      header = buildHeader({
        objectId: v.objectId, objectType: input.objectType, tenantId: ctx.tenantId, domainId: ctx.domainId, scope: ctx.scope,
        objectVersion: String(v.version), lifecycleState: v.lifecycle, owningComponent: 'CP-OBJ-01', accountableOwner: actor,
        sourceObjectIds: prov.source_object_ids,
        ...(input.eventTime === undefined && input.time?.event !== undefined ? {} : { eventTime: iso(input.eventTime) }),
        ...(input.observationTime === undefined && input.time?.observation !== undefined ? {} : { observationTime: iso(input.observationTime) }),
        ...(input.validFrom === undefined && input.time?.valid_from !== undefined ? {} : { validFrom: iso(input.validFrom) }),
        ...(input.validTo === undefined && input.time?.valid_to !== undefined ? {} : { validTo: iso(input.validTo) }),
        recordedAt: recordedAt.toISOString(),
        ...(input.timePrecision === undefined ? {} : { timePrecision: input.timePrecision }),
        sourceClockQuality: input.sourceClockQuality ?? 'trusted',
        truthState, syntheticState, confidence: null, uncertainty: null,
        evidenceRefs: prov.evidence_refs, provenanceRef: null, methodRef: prov.method_ref, contradictionRefs: [], corroborationRefs: [], humanRefs: prov.human_refs,
        classification: input.classification, purposeScope: input.purposeScope,
        rightsProfile: null, residencyProfile: null, retentionProfile: null, accessPolicyRef: null,
        qualityProfile: null, qualityState: null, freshnessState: null,
        schemaRef: `${input.objectType}@${schemaVersion}`, ontologyRef: null,
        correctionOf: v.correctionOf, supersedes: v.correctionOf, // corrected version is superseded for current use
        withdrawalReason: null, auditCorrelationId: correlationId, contentRef: null,
      }, input.time === undefined ? {} : { time: input.time });
    } catch (e) {
      if (e instanceof HeaderBuildError) throw bad('EYE_TMP_001', correlationId, e.message, 400);
      throw e;
    }
    const hv = validateHeader(header);
    if (!hv.ok) {
      throw bad('EYE_REQ_001', correlationId, `canonical header invalid: ${(hv.errors ?? []).join('; ')}`, 422);
    }
    const digest = canonicalHeaderDigest(header, input.payload);

    // Gate-2 §5: the ONLY canonical write path. objects.admit_version re-checks
    // the complete 40+3 field registry, RECOMPUTES the header+payload digest
    // inside the trusted boundary, and refuses a supplied digest that does not
    // bind them. No runtime role holds direct INSERT on canonical_objects.
    await cap.admitObject(header, input.payload, digest, input.time === undefined ? undefined : timeDeclaration(input.time)); // B50 hd: the stated times

    const stored = (await cap
      .readCanonicalObjects()
      .selectAll()
      .where('object_id' as never, '=', v.objectId as never)
      .where('object_version' as never, '=', v.version as never)
      .executeTakeFirstOrThrow()) as ObjectRow;

    // R5 — storage round-trip verification INSIDE the same transaction: the
    // stored row must rebuild to a header whose digest equals what we computed
    // and persisted. A lossy or reordered mapping aborts (rolls back) here.
    const rebuilt = rebuildHeaderFromRow(stored);
    const roundTrip = canonicalHeaderDigest(rebuilt, stored['payload'] as Record<string, unknown>);
    if (roundTrip !== digest || stored.content_digest !== digest) {
      throw bad('EYE_STA_003', correlationId, 'storage round-trip digest verification failed — write aborted', 500);
    }

    return stored;
  }
}

/**
 * B10-F4 (found while closing B10-F1 at the governed boundary): the generic object read serves the HEADER of an
 * audience-governed object and never its content. A memory item's content is a retrieval's (`memory.item.retrieve`
 * under a declared purpose, within the version's audience roles and classification), a briefing's is a briefing
 * read's (`briefing.read`, the room's members, the cited memory versions' audiences) — this route holds neither rule
 * and had served a role-restricted, classification-restricted memory version whole to any holder of `objects.read`.
 */
const AUDIENCE_GOVERNED: Record<string, string> = {
  MEM: 'the content of a memory item is read through memory.item.retrieve under a declared purpose, within the version\'s audience',
  BRF: 'the content of a briefing is read through briefing.read, within the cited memory versions\' audiences',
};
export function servedRow(row: ObjectRow): ObjectRow {
  const rule = AUDIENCE_GOVERNED[String(row.object_type)];
  if (rule === undefined) return row;
  return { ...row, payload: null, content_withheld: { object_type: row.object_type, reason: rule } };
}

/** Rebuild the 43-field canonical header from a stored row (round-trip check). B50 hd: the builder's (header-builder.ts), re-exported. */
export function rebuildHeaderFromRow(row: ObjectRow): CanonicalHeader {
  return rebuildFromRow(row);
}
