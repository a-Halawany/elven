#!/usr/bin/env node
/**
 * Controls for audit/summarise-units.mjs — the S7 accounting must be EVIDENCE-BACKED and FAIL CLOSED
 * (Codex, 2026-09-12: the earlier summariser exited 0 and reduced the unfinished total for a unit marked
 * verified:all with no leg evidence, and accepted `saas=;private=;onprem=` as three accepted legs).
 *
 * Three fixture runs in a temporary directory, never touching the tracked audit:
 *   N1 — a mandatory three-leg unit marked verified:all with NO legs_verified        → exit 1, summary untouched
 *   N2 — a mandatory three-leg unit marked verified:all with EMPTY pointers          → exit 1, summary untouched, no leg counted
 *   P1 — the same unit with a validated pointer per leg (files that exist, on paths that name the leg)
 *                                                                                    → exit 0, summary written, the unit
 *                                                                                      finished, three legs accepted
 * plus P2 — the tracked audit itself: exit 0 and the committed section up to date (`--check`).
 * Run: node audit/summarise-units.controls.mjs   (exit 1 on any failed control)
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync, existsSync, cpSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const script = join(here, 'summarise-units.mjs');
const HEADER = 'unit_id,statement,condition,source_rows,primary_source,capability_area,mandatory,profiles,evidence_class,status,legs_verified,package,evidence,remaining_work,notes';
const esc = (v) => (/[",\n]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v);
const row = (o) => HEADER.split(',').map((c) => esc(o[c] ?? '')).join(',');
const base = { statement: 'a fixture obligation', condition: 'All profiles.', source_rows: 'V0:C-001', primary_source: 'V0:C-001', capability_area: 'memory-graph', mandatory: 'yes', profiles: 'saas|private|onprem', evidence_class: 'harness', status: 'open', legs_verified: '', package: 'P3', evidence: '', remaining_work: '', notes: '' };
const SENTINEL = '# a previous VALID summary\n\nkept as it was\n\n## Acceptance units (from audit/acceptance-units, generated by audit/summarise-units.mjs)\n\nUnits: 0.\n';

let failed = 0;
const check = (label, ok, detail) => { console.log(`${ok ? '✓' : '✗'} ${label}${detail ? ` — ${detail}` : ''}`); if (!ok) failed += 1; };

function fixture(name, units) {
  const root = mkdtempSync(join(tmpdir(), `summarise-controls-${name}-`));
  mkdirSync(join(root, 'audit', 'acceptance-units'), { recursive: true });
  mkdirSync(join(root, 'audit', 'requirements'), { recursive: true });
  // The requirement rows the fixture units cite, and the alias table the CAP check reads (the tracked ones).
  writeFileSync(join(root, 'audit', 'requirements', 'v00-v01.csv'), 'id,volume,chapter\nC-001,V0,1\n');
  for (const f of ['v08.csv', 'v09.csv']) cpSync(join(here, 'requirements', f), join(root, 'audit', 'requirements', f));
  cpSync(join(here, 'CAP_ALIASES.md'), join(root, 'audit', 'CAP_ALIASES.md'));
  writeFileSync(join(root, 'audit', 'acceptance-units', 'group-x.csv'), `${HEADER}\n${units.map((u) => row({ ...base, ...u })).join('\n')}\n`);
  writeFileSync(join(root, 'audit', 'SUMMARY.md'), SENTINEL);
  return root;
}
function run(root, extra = []) {
  const args = [script, '--units', join(root, 'audit', 'acceptance-units'), '--requirements', join(root, 'audit', 'requirements'), '--aliases', join(root, 'audit', 'CAP_ALIASES.md'), '--summary', join(root, 'audit', 'SUMMARY.md'), '--root', root, ...extra];
  try { return { code: 0, out: execFileSync('node', args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }), err: '' }; }
  catch (e) { return { code: e.status ?? 1, out: String(e.stdout ?? ''), err: String(e.stderr ?? '') }; }
}
const summaryOf = (root) => readFileSync(join(root, 'audit', 'SUMMARY.md'), 'utf8');

// ── N1: verified:all with no leg evidence ────────────────────────────────────
{
  const root = fixture('n1', [{ unit_id: 'AU-XXX-0001', status: 'verified:all', legs_verified: '' }, { unit_id: 'AU-XXX-0002' }]);
  const r = run(root);
  check('N1 exits non-zero', r.code !== 0, `exit ${r.code}`);
  check('N1 names the unit and the missing legs', /AU-XXX-0001: verified:all without validated evidence on every leg \(saas,private,onprem\)/.test(r.err), r.err.trim().split('\n').slice(0, 3).join(' | '));
  check('N1 leaves the previous valid summary untouched', summaryOf(root) === SENTINEL);
  check('N1 still counts the unit as unfinished (inconsistent), not as finished', /mandatory unfinished 2 \(open 1 \+ verified:local 0 \+ verified:ci 0 \+ inconsistent 1; with accepted legs 0\); verified:all 0/.test(r.out), r.out.trim());
}
// ── N2: verified:all with empty pointers on every leg ───────────────────────
{
  const root = fixture('n2', [{ unit_id: 'AU-XXX-0001', status: 'verified:all', legs_verified: 'saas=;private=;onprem=' }, { unit_id: 'AU-XXX-0002' }]);
  const r = run(root);
  check('N2 exits non-zero', r.code !== 0, `exit ${r.code}`);
  check('N2 refuses each empty pointer by leg', ['saas', 'private', 'onprem'].every((l) => new RegExp(`AU-XXX-0001: leg ${l}: no evidence pointer`).test(r.err)), r.err.trim().split('\n').slice(0, 4).join(' | '));
  check('N2 counts no accepted leg', /legs saas 0\/2, private 0\/2, onprem 0\/2/.test(r.out), r.out.trim());
  check('N2 leaves the previous valid summary untouched', summaryOf(root) === SENTINEL);
}
// ── N3: a pointer to a file that does not exist, and one on a path that names another leg ──
{
  const root = fixture('n3', [{ unit_id: 'AU-XXX-0001', status: 'verified:all', legs_verified: 'saas=docs/acceptance/saas/AU-XXX-0001.md;private=docs/acceptance/private/AU-XXX-0001.md;onprem=docs/acceptance/saas/AU-XXX-0001.md' }]);
  mkdirSync(join(root, 'docs', 'acceptance', 'saas'), { recursive: true });
  writeFileSync(join(root, 'docs', 'acceptance', 'saas', 'AU-XXX-0001.md'), 'signed result (fixture)\n');
  const r = run(root);
  check('N3 exits non-zero', r.code !== 0, `exit ${r.code}`);
  check('N3 refuses the pointer that resolves nowhere', /AU-XXX-0001: leg private: pointer 'docs\/acceptance\/private\/AU-XXX-0001.md' does not resolve/.test(r.err), r.err.trim().split('\n').slice(0, 4).join(' | '));
  check('N3 refuses the pointer whose path names another leg', /AU-XXX-0001: leg onprem: pointer 'docs\/acceptance\/saas\/AU-XXX-0001.md' does not name the leg onprem/.test(r.err));
  check('N3 leaves the previous valid summary untouched', summaryOf(root) === SENTINEL);
}
// ── P1: validated evidence on every leg ─────────────────────────────────────
{
  const root = fixture('p1', [{ unit_id: 'AU-XXX-0001', status: 'verified:all', legs_verified: 'saas=docs/acceptance/saas/AU-XXX-0001.md;private=docs/acceptance/private/AU-XXX-0001.md#result;onprem=docs/acceptance/onprem/AU-XXX-0001.md:12-40' }, { unit_id: 'AU-XXX-0002' }]);
  for (const leg of ['saas', 'private', 'onprem']) { mkdirSync(join(root, 'docs', 'acceptance', leg), { recursive: true }); writeFileSync(join(root, 'docs', 'acceptance', leg, 'AU-XXX-0001.md'), `signed result for ${leg} (fixture)\n`); }
  const r = run(root);
  check('P1 exits zero', r.code === 0, `exit ${r.code} ${r.err.trim()}`);
  check('P1 finishes the evidenced unit and keeps the other open', /mandatory unfinished 1 \(open 1 \+ verified:local 0 \+ verified:ci 0; with accepted legs 0\); verified:all 1/.test(r.out), r.out.trim());
  check('P1 accepts one leg each', /legs saas 1\/2, private 1\/2, onprem 1\/2/.test(r.out));
  check('P1 writes the summary', summaryOf(root) !== SENTINEL && /Units: 2\./.test(summaryOf(root)));
  // and `--check` agrees with what it just wrote
  const c = run(root, ['--check']);
  check('P1 --check passes on the written summary', c.code === 0 && /check: the committed acceptance-unit section matches/.test(c.out), c.out.trim() + c.err.trim());
}
// ── P2: the tracked audit itself ────────────────────────────────────────────
{
  let r;
  try { r = { code: 0, out: execFileSync('node', [script, '--check'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], cwd: join(here, '..') }), err: '' }; }
  catch (e) { r = { code: e.status ?? 1, out: String(e.stdout ?? ''), err: String(e.stderr ?? '') }; }
  check('P2 the tracked audit passes --check (no problem; the committed section is current)', r.code === 0, (r.err || r.out).trim().split('\n').slice(0, 3).join(' | '));
  const m = /mandatory unfinished (\d+) \(open (\d+) \+ verified:local (\d+) \+ verified:ci (\d+); with accepted legs (\d+)\); verified:all (\d+)/.exec(r.out);
  check('P2 the tracked split is evidence-backed (no accepted leg, no verified:all)', m !== null && m[5] === '0' && m[6] === '0', m ? `${m[1]} = ${m[2]} + ${m[3]} + ${m[4]}` : r.out.trim());
}
console.log(failed === 0 ? 'controls: all passed' : `controls: ${failed} FAILED`);
process.exit(failed === 0 ? 0 : 1);
